package com.athenstours.dto;

import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.math.BigDecimal;

/** The uuid identifying which Tour to update comes from the URL path, not from this body. */
public record TourUpdateDTO(

        @NotBlank(message = "Name is required")
        @Size(min = 2, max = 150, message = "Name must be between 2 and 150 characters")
        String name,

        @Size(max = 2000, message = "Description must be at most 2000 characters")
        String description,

        @NotNull(message = "Price is required")
        @DecimalMin(value = "0.01", message = "Price must be greater than zero")
        BigDecimal price,

        @NotNull(message = "Duration is required")
        @Positive(message = "Duration must be a positive number of minutes")
        Integer durationMinutes,

        @NotNull(message = "Category is required")
        Long categoryId
) {
}
